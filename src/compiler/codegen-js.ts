export function sanitizeIdentifierJs(name: string): string {
  // In JavaScript, $ and _ are naturally valid identifier characters
  let res = name.replace(/@/g, '_at_');
  if (!/^[a-zA-Z_$]/.test(res)) {
    res = '_' + res;
  }
  return res;
}

